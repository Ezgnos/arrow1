<?php
declare(strict_types=1);

// Задача 2. Захват переменных из внешней области

$discount = 0.9; // скидка 10%

// $discount нигде не перечисляется: fn захватывает её автоматически
$applyDiscount = fn(float $price): float => $price * $discount;

foreach ([1000, 500, 250] as $price) { // цикл только для вывода
    echo "Цена {$price} со скидкой: " . $applyDiscount($price) . PHP_EOL;
}

$discount = 0.5; // меняем переменную ПОСЛЕ создания функции
echo 'После $discount = 0.5, цена 1000: ' . $applyDiscount(1000) . PHP_EOL;

/*
 * Результат не изменился (900, а не 500), потому что fn захватывает внешние переменные
 * ПО ЗНАЧЕНИЮ и В МОМЕНТ СОЗДАНИЯ функции: внутрь попадает копия значения 0.9.
 * Позднее изменение внешней $discount на копию не влияет.
 */

// Дополнительно: функция, использующая сразу две внешние переменные
$rate = 90.0; // курс: рублей за 1 доллар
// Создана ПОСЛЕ изменения скидки, поэтому захватит $discount = 0.5 и $rate = 90.0
$toRubles = fn(float $usd): float => $usd * $rate * $discount;

echo '100 USD в рублях с коэффициентом скидки: ' . $toRubles(100) . PHP_EOL;
